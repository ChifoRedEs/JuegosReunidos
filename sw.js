const FUENTES_CSS = 'https://fonts.googleapis.com/css2?family=Baloo+2:wght@600;800&family=Chewy&family=Fraunces:opsz,wght@9..144,700;9..144,900&family=Nunito:wght@500;700;800&display=swap';
