async function descargarTodo() {
  if (descargando) return;
  descargando = true; cancelarDescarga = false;
  try {
    const [cv, cc, cd] = await Promise.all([caches.open(VERSION), caches.open(CARTAS), caches.open(DICC)]);
    const cola = [...EXTRA.map(u => [cv, u]), ...CARTAS_TODO.map(u => [cc, u]), ...DICC_TODO.map(u => [cd, u])];
    let hecho = 0, fallos = 0, i = 0; const total = cola.length;
    const trabajador = async () => {
      while (!cancelarDescarga) {
        const k = i++; if (k >= total) return;
        const [c, u] = cola[k];
        try {
          if (!(await c.match(u, { ignoreSearch: true }))) { const r = await fetch(u, { cache: 'reload' }); if (r.ok) await c.put(u, r); else fallos++; }
        } catch { fallos++; }
        hecho++; if (hecho % 8 === 0 || hecho === total) avisar({ tipo: 'descarga', hecho, total, fallos });
      }
    };
    await Promise.all(Array.from({ length: 6 }, trabajador));
    await avisar({ tipo: 'descarga-fin', hecho, total, fallos, cancelada: cancelarDescarga });
  } finally { descargando = false; }
  await estadoDescarga();
}
